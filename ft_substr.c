#include "libft.h"

char	*ft_substr(char const *s, unsigned int start, size_t len)
{
	size_t	slen;
	size_t	clone;
	char	*dest;

	if (!s)
		return (NULL);
	slen = ft_strlen(s);
	if (start >= slen || len == 0)
		return (ft_strdup(""));
	clone = slen - start;
	if (len < clone)
		clone = len;
	dest = malloc(clone + 1);
	if (!dest)
		return (NULL);
	ft_memcpy(dest, s + start, clone);
	dest[clone] = '\0';
	return (dest);
}
