#include "libft.h"

char	*ft_strdup(const char *src)
{
	char	*dest;
	size_t	length;

	length = ft_strlen(src);
	dest = malloc(length + 1);
	if (!dest)
		return (NULL);
	ft_memcpy(dest, src, length + 1);
	return (dest);
}
